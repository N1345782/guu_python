"""
Задача 05-04. Квадраты

Прочитайте целое число n, затем n целых чисел — каждое с отдельной строки.
Соберите список их квадратов и выведите его одной строкой через пробел.

Пример
------
Ввод:
4
1
5
-2
3
Вывод:
1 25 4 9
"""

n = int(input())

# TODO: соберите список квадратов и выведите через пробел
n = int(input())
squares = []
for _ in range(n):
    x = int(input())
    squares.append(x * x)

print(" ".join(str(s) for s in squares))
