# TODO: прочитайте цену, количество и процент скидки

# TODO: вычислите и выведите три строки чека

price = float(input())
quantity = int(input())
discount_percent = int(input())

total_cost = price * quantity
discount_amount = total_cost * discount_percent / 100
final_price = total_cost - discount_amount

print(f"Стоимость: {round(total_cost, 2)}")
print(f"Скидка: {round(discount_amount, 2)}")
print(f"К оплате: {round(final_price, 2)}")