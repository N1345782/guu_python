"""
Задача 04-03. Сколько слов

Прочитайте предложение (слова разделены пробелами, возможно не одним)
и выведите количество слов.

Пример
------
Ввод:
один два   три
Вывод:
3
"""

# TODO: разбейте строку на слова и посчитайте их

s = input()
words = 0
in_word = False
for ch in s:
    if ch != " ":
        if not in_word:
            words += 1
            in_word = True
    else:
        in_word = False
print(words)