"""
Задача 02-16. Время года

Прочитайте порядковый номер месяца (целое число). Выведите время года:

- 12, 1, 2 — «зима»;
- 3, 4, 5 — «весна»;
- 6, 7, 8 — «лето»;
- 9, 10, 11 — «осень»;
- любой другой номер — «ошибка».

Пример
------
Ввод:
4
Вывод:
весна
"""

# TODO: прочитайте номер месяца и выведите время года
month = int(input())

match month:
    case 12 | 1 | 2:
        print("зима")
    case 3 | 4 | 5:
        print("весна")
    case 6 | 7 | 8:
        print("лето")
    case 9 | 10 | 11:
        print("осень")
    case _:
        print("ошибка")
